/** ตัวคูณการสลายของการปล่อยตามเวลา — ค่าเดิมของโปรเจกต์ ห้ามเปลี่ยนโดยไม่ตั้งใจ */
const DECAY = 1.6;

/**
 * @param {number} nWindow  จำนวนชั่วโมงที่จำลอง (ความยาว timeline)
 * @param {number} [nBurn]  จำนวนชั่วโมงที่ไฟยังเผาอยู่ · ไม่ใส่ = เผาตลอดช่วง (พฤติกรรมเดิม)
 * @returns {{w:number[], p:number[]}} w = สัดส่วนการปล่อย รวม 1 · p = ความคืบหน้าการเผา 0..1
 */
export function hourWeights(nWindow, nBurn) {
  const win = Math.max(1, Math.round(nWindow) || 0);
  const burn = Math.min(win, Math.max(1, Math.round(nBurn ?? win) || 0));

  const w = [], p = [];
  let s = 0;
  for (let i = 0; i < win; i++) {
    if (i < burn) {
      const x = (i + 0.5) / burn;
      const v = Math.exp(-DECAY * x);
      w.push(v); p.push(x); s += v;
    } else {
      // ไฟดับแล้ว — ไม่ปล่อยอะไรอีก แต่ความคืบหน้าค้างที่ 1 เพราะเผาไปหมดแล้วจริงๆ
      w.push(0); p.push(1);
    }
  }
  // normalize เฉพาะชั่วโมงที่เผา มวลรวมจึงเป็น 1 เสมอไม่ว่าช่วงจำลองจะยาวแค่ไหน
  return { w: w.map(v => (s > 0 ? v / s : 0)), p };
}
